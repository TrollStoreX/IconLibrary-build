import Foundation

struct Country: Identifiable {
    let nameKey: String
    let code: String

    var id: String { code }

    var flag: String {
        String(String.UnicodeScalarView(code.unicodeScalars.compactMap { Unicode.Scalar(0x1F1A5 + $0.value) }))
    }

    var localizedName: String {
        .localized(nameKey)
    }

    static func matching(_ code: String) -> Country? {
        all.first { $0.code == code }
    }
}

extension Country {
    private static let preferredCodeKey = "selectedCountryCode"

    static var preferredCode: String {
        get { UserDefaults.standard.string(forKey: preferredCodeKey) ?? "CN" }
        set { UserDefaults.standard.set(newValue, forKey: preferredCodeKey) }
    }
}

